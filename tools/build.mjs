// Builds index.html, the one-file game, from the sources in src/, and writes data.json for the balance sim.
// Plain Node, no packages (only --release needs one, esbuild: run npm install first).
//
//   node tools/build.mjs          write index.html and data.json
//   node tools/build.mjs --check  fail if the committed index.html or data.json is out of date with src/
//   node tools/build.mjs --release  also write dist/Etherwake.html (the page to share: no dev panel, no test hook) and dist/music/
//
// src/index.html is the page. On it, a line <!--#include name--> is replaced by that file from src/, and the line
// <!--#modules--> by the game's script modules from src/js/, joined in the order below. They all run inside one
// function, so a module can use anything another one defines, as long as it is only used once the game is running.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');

/* in the order they run: tables first, then state, then each system, then the loop and the wiring that starts it */
export const MODULES = ['data', 'state', 'ether', 'regions', 'music', 'sound', 'ship', 'hulls', 'particles', 'world', 'damage', 'enemies', 'groups', 'designs', 'waves', 'armour', 'hazards', 'standins', 'copies', 'pacts', 'echoes', 'stations',
  'weapons', 'shipyard', 'hud', 'log', 'sim', 'draw', 'loop', 'save', 'dev', 'boot'];

/* line endings are read as \n, so a Windows checkout (CRLF) builds and checks the same as any other */
const read = file => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const body = text => (text.endsWith('\n') ? text.slice(0, -1) : text);

/* the release page leaves out everything between a dev-start line and the next dev-end line (script: slash-star-hash-dev-star-slash and its -end twin; page: the same as comments):
   the dev panel, its buttons and the hook the tests use. The normal page keeps them, as comments */
export function stripDev(text) {
  let drop = false;
  return text.split('\n').filter(line => {
    const t = line.trim();
    if (t === '/*#dev*/' || t === '<!--#dev-->') { drop = true; return false; }
    if (t === '/*#enddev*/' || t === '<!--#enddev-->') { drop = false; return false; }
    return !drop;
  }).join('\n');
}

/* the shared page also loses every comment: they hold working notes, not anything to ship. esbuild rebuilds the code from its syntax tree, so a string or a regular
   expression that holds slashes is never taken for a comment; the page's own comments (<!-- -->) go too, outside the script and the styles */
export function stripComments(html) {
  let esbuild;
  try { esbuild = createRequire(import.meta.url)('esbuild'); } catch { throw new Error('--release needs esbuild: run npm install first'); }
  const pack = (code, loader) => esbuild.transformSync(code, { loader, legalComments: 'none', minifyWhitespace: true, charset: 'utf8' }).code.trim();
  return html.split(/(<script>[\s\S]*?<\/script>|<style>[\s\S]*?<\/style>)/).map((part, i) => {
    if (i % 2 === 0) return part.replace(/<!--[\s\S]*?-->\n?/g, '');
    return part.startsWith('<script>') ? '<script>' + pack(part.slice(8, -9), 'js') + '</script>' : '<style>' + pack(part.slice(7, -8), 'css') + '</style>';
  }).join('');
}

export function buildPage(release = false) {
  const modules = MODULES.map(m => body(read(path.join(SRC, 'js', m + '.js')))).join('\n');
  const page = read(path.join(SRC, 'index.html')).split('\n').map(line => {
    const inc = line.match(/^<!--#include ([\w.-]+)-->$/);
    if (inc) return body(read(path.join(SRC, inc[1])));
    return line === '<!--#modules-->' ? modules : line;
  }).join('\n');
  return release ? stripComments(stripDev(page)) : page;
}

/* the tuning tables, read straight out of data.js, so the sim can never disagree with the game about a number */
export function buildData() {
  const fakeEl = { getContext: () => ({}), style: {}, classList: { toggle() {} } };
  const context = vm.createContext({
    document: { getElementById: () => fakeEl, documentElement: fakeEl },
    window: {}, matchMedia: () => ({ matches: false }), Math,
  });
  const code = read(path.join(SRC, 'js', 'data.js')) +
    '\n;({TUNE:typeof TUNE==="undefined"?{}:TUNE,BT,ET,UNLOCK,ULK,MOODS:MOODS.map(m=>m.name),WORLD,CELL});';
  const data = vm.runInContext(code, context, { filename: 'src/js/data.js' });
  return JSON.stringify({ note: 'Generated by tools/build.mjs from src/js/data.js. Do not edit.', ...data }, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = [[path.join(ROOT, 'index.html'), buildPage()], [path.join(ROOT, 'data.json'), buildData()]];
  if (process.argv.includes('--check')) {
    const stale = out.filter(([file, text]) => !fs.existsSync(file) || read(file) !== text).map(([file]) => path.relative(ROOT, file));
    if (stale.length) {
      console.error(`Out of date with src/: ${stale.join(', ')}. Run: node tools/build.mjs`);
      process.exit(1);
    }
    console.log('index.html and data.json match src/');
  } else {
    for (const [file, text] of out) fs.writeFileSync(file, text);
    console.log(`Built index.html (${Math.round(out[0][1].length / 1024)} KB) and data.json`);
    if (process.argv.includes('--release')) {
      const dist = path.join(ROOT, 'dist');
      fs.mkdirSync(path.join(dist, 'music'), { recursive: true });
      const html = buildPage(true);
      fs.writeFileSync(path.join(dist, 'Etherwake.html'), html);
      fs.copyFileSync(path.join(ROOT, 'music', 'spaceify.webm'), path.join(dist, 'music', 'spaceify.webm'));
      console.log(`Built dist/Etherwake.html (${Math.round(html.length / 1024)} KB) and dist/music/spaceify.webm: share the two together`);
    }
  }
}
